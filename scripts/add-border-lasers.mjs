#!/usr/bin/env node
// Adds animated "running line" lasers along the border of README SVG images.
//   node scripts/add-border-lasers.mjs public/zyntheor-architecture.svg public/status-cards.svg
//   node scripts/add-border-lasers.mjs --remove public/status-cards.svg
// - Reads each file's own viewBox/geometry; nothing is hard-coded to one design.
// - Frame mode: if the file has one large outer <rect>, the laser follows that rect.
// - Card mode: otherwise every <g transform="translate(x y)"> whose first child is a rounded <rect> gets its own laser.
// - Idempotent: previously injected blocks (between zy-laser markers) are removed and re-created.
// - Decoration only: the laser colour is neutral cyan and never encodes PASS/FAIL state.
// NOTE: public/status-cards.svg is regenerated by scripts/gen-status-cards.mjs; run this script again after regenerating it.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';

const args = process.argv.slice(2);
const REMOVE = args.includes('--remove');
const files = args.filter((a) => !a.startsWith('--'));
if (!files.length) {
  console.error('usage: node scripts/add-border-lasers.mjs [--remove] <file.svg> [...]');
  process.exit(2);
}

const START = '<!-- zy-laser:start -->';
const END = '<!-- zy-laser:end -->';
const BLOCK_RE = new RegExp(`\\s*${START}[\\s\\S]*?${END}`, 'g');
const num = (s) => (s === undefined ? NaN : parseFloat(s));
const attr = (tag, name) => {
  const m = tag.match(new RegExp(`\\s${name}="([^"]*)"`));
  return m ? m[1] : undefined;
};

const CSS = `<style>
    @keyframes zy-lz  { from { stroke-dashoffset: 100; } to { stroke-dashoffset: 0; } }
    @keyframes zy-lzr { from { stroke-dashoffset: 0; }   to { stroke-dashoffset: 100; } }
    .zy-lz  { stroke-dasharray: 14 86; animation: zy-lz 6s linear infinite; }
    .zy-lzr { stroke-dasharray: 9 91;  animation: zy-lzr 8s linear infinite; }
    @media (prefers-reduced-motion: reduce) { .zy-lz, .zy-lzr { animation: none; } }
  </style>`;

function defs(W, H) {
  return `<defs>
    <linearGradient id="zy-laser-g" x1="0" y1="0" x2="1" y2="0"><stop offset="0" stop-color="#10B981"/><stop offset="0.5" stop-color="#2DD4BF"/><stop offset="1" stop-color="#38BDF8"/></linearGradient>
    <filter id="zy-laser-f" filterUnits="userSpaceOnUse" x="-20" y="-20" width="${W + 40}" height="${H + 40}"><feGaussianBlur stdDeviation="2.2" result="b"/><feMerge><feMergeNode in="b"/><feMergeNode in="SourceGraphic"/></feMerge></filter>
  </defs>`;
}

function laserRects(g, widthMain, delay) {
  const geo = `x="${g.x}" y="${g.y}" width="${g.w}" height="${g.h}" rx="${g.rx}" fill="none" stroke-linecap="round" pathLength="100"`;
  return `<rect ${geo} stroke="url(#zy-laser-g)" stroke-width="${widthMain}" class="zy-lz" style="animation-delay:${delay}s" filter="url(#zy-laser-f)"/>
    <rect ${geo} stroke="#38BDF8" stroke-width="${(widthMain * 0.7).toFixed(2)}" class="zy-lzr" style="animation-delay:${delay}s" filter="url(#zy-laser-f)"/>`;
}

function rectGeo(tag) {
  const g = { x: num(attr(tag, 'x') ?? '0'), y: num(attr(tag, 'y') ?? '0'), w: num(attr(tag, 'width')), h: num(attr(tag, 'height')), rx: num(attr(tag, 'rx') ?? '0') };
  return [g.x, g.y, g.w, g.h].every(Number.isFinite) ? g : null;
}

function applyLaser(file) {
  if (!existsSync(file)) { console.error(`SKIP  ${file} (not found)`); return false; }
  let svg = readFileSync(file, 'utf8');
  svg = svg.replace(BLOCK_RE, '');
  if (REMOVE) { writeFileSync(file, svg); console.log(`CLEAN ${file}`); return true; }

  const vb = (svg.match(/<svg[^>]*\sviewBox="([^"]+)"/) || [])[1];
  const parts = vb ? vb.split(/[\s,]+/).map(Number) : [];
  if (parts.length !== 4 || parts.some((n) => !Number.isFinite(n))) { console.error(`SKIP  ${file} (no usable viewBox)`); return false; }
  const [, , W, H] = parts;

  // Look at drawable shapes only (ignore defs, patterns, masks, clip paths, filters, styles).
  const drawable = svg.replace(/<(defs|pattern|mask|clipPath|filter|style|symbol)\b[\s\S]*?<\/\1>/g, '');

  // Frame mode: the largest rect that covers (almost) the whole image, wherever it sits (root or inside a <g>).
  const bigRects = (drawable.match(/<rect\b[^>]*>/g) || [])
    .map(rectGeo)
    .filter((g) => g && g.w >= W * 0.9 && g.h >= H * 0.85);
  const frame = bigRects.find((g) => g.rx > 0) || bigRects[0];

  let body = '';
  let mode = '';
  if (frame) {
    mode = 'frame';
    const g = { ...frame };
    const touchesEdge = g.x < 2 || g.y < 2 || g.x + g.w > W - 2 || g.y + g.h > H - 2;
    if (touchesEdge) { g.x = 1.5; g.y = 1.5; g.w = W - 3; g.h = H - 3; mode = 'frame (full-bleed, inset to image edge)'; }
    body = laserRects(g, 2.4, 0);
  } else {
    // Card mode.
    const cards = [...drawable.matchAll(/<g\s+transform="translate\(\s*([-\d.]+)[\s,]+([-\d.]+)\s*\)"\s*>\s*(<rect\b[^>]*>)/g)];
    const out = [];
    cards.forEach((m, i) => {
      const g = rectGeo(m[3]);
      if (!g || g.w < 40 || g.h < 24) return;
      out.push(`<g transform="translate(${m[1]} ${m[2]})">\n    ${laserRects(g, 1.8, -(i * 1.5))}\n  </g>`);
    });
    if (out.length) {
      mode = `cards x${out.length}`;
      body = out.join('\n  ');
    } else {
      // Last resort: follow the image edge itself.
      mode = 'image edge (fallback: no frame or cards detected)';
      body = laserRects({ x: 2, y: 2, w: W - 4, h: H - 4, rx: Math.min(16, Math.floor(Math.min(W, H) / 6)) }, 2.4, 0);
    }
  }

  const block = `\n  ${START}\n  ${CSS}\n  ${defs(W, H)}\n  ${body}\n  ${END}\n`;
  const idx = svg.lastIndexOf('</svg>');
  if (idx < 0) { console.error(`SKIP  ${file} (no closing </svg>)`); return false; }
  writeFileSync(file, svg.slice(0, idx) + block + svg.slice(idx));
  console.log(`OK    ${file}  (${mode}, viewBox ${W}x${H})`);
  return true;
}

const results = files.map(applyLaser);
process.exit(results.every(Boolean) ? 0 : 1);
